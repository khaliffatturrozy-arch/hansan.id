-- ═════════════════════════════════════════════════════════════════════════════
-- HANSAN — Phase B: Tenant-Safe Data Foundation
--
-- PURPOSE
--   Make tenant ownership explicit and database-enforced for the catalog
--   (Category / MenuItem) and for Order, resolve the platform-role ownership
--   contradiction, add the composite indexes required by real query patterns,
--   and enforce monetary invariants at the database level.
--
-- SCOPE
--   Schema only. No business row is created, updated, or deleted. The initial
--   production database is allowed to remain empty and stays empty.
--
-- SAFETY
--   FAIL-CLOSED. If the target database already contains catalog or order rows
--   that cannot be attributed to a tenant without guessing, the migration aborts
--   BEFORE any DDL executes and tells the operator exactly what must be
--   backfilled. It never invents organization/outlet/staff identifiers, and it
--   never deletes data.
--
-- GENERATOR NOTE
--   The DDL in section 3 was produced by:
--     npx prisma migrate diff \
--       --from-schema-datamodel <pre-Phase-B schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
--   Sections 1 and 4 are hand-written. Prisma cannot express CHECK constraints,
--   so they are managed as raw SQL; they are invisible to Prisma's schema model
--   and therefore will not be dropped by `prisma migrate dev`.
-- ═════════════════════════════════════════════════════════════════════════════

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. FAIL-CLOSED PRE-FLIGHT GUARD (runs before any DDL)
-- ─────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE
  v_categories bigint;
  v_menu_items bigint;
  v_orphans    bigint;
BEGIN
  SELECT count(*) INTO v_categories FROM "Category";
  SELECT count(*) INTO v_menu_items FROM "MenuItem";

  IF v_categories > 0 OR v_menu_items > 0 THEN
    RAISE EXCEPTION
      'HANSAN_PHASE_B_BACKFILL_REQUIRED: % "Category" row(s) and % "MenuItem" row(s) already exist. '
      'This migration makes catalog rows tenant-owned and cannot infer which organization owns them. '
      'Attribute every existing Category/MenuItem row to the correct organization before applying this migration. '
      'Do NOT fabricate organization identifiers. No row was modified.',
      v_categories, v_menu_items;
  END IF;

  SELECT count(*) INTO v_orphans
    FROM "Order"
   WHERE "organizationId" IS NULL
      OR "outletId" IS NULL
      OR "staffId" IS NULL;

  IF v_orphans > 0 THEN
    RAISE EXCEPTION
      'HANSAN_PHASE_B_BACKFILL_REQUIRED: % "Order" row(s) have a NULL organizationId, outletId, or staffId. '
      'These columns become NOT NULL in this migration. Attribute every order to the organization, outlet, '
      'and staff that produced it, or archive test orders, before applying. '
      'Do NOT fabricate identifiers. No row was modified.',
      v_orphans;
  END IF;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. DROP LEGACY CONSTRAINTS REPLACED BY TENANT-SCOPED EQUIVALENTS
-- ─────────────────────────────────────────────────────────────────────────────

-- Global category slug uniqueness made multi-tenancy impossible; replaced by
-- the per-organization unique index created in section 3.
ALTER TABLE "MenuItem" DROP CONSTRAINT "MenuItem_categoryId_fkey";
ALTER TABLE "Order" DROP CONSTRAINT "Order_staffId_fkey";
DROP INDEX "Category_slug_key";
DROP INDEX "MenuItem_categoryId_idx";
DROP INDEX "Order_idempotencyKey_idx";
DROP INDEX "Order_organizationId_idx";

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. TENANT OWNERSHIP, RELATIONSHIPS AND INDEXES (generated by prisma migrate diff)
-- ─────────────────────────────────────────────────────────────────────────────

-- 3a. Platform roles are no longer owned by a tenant organization.
ALTER TABLE "Role" ALTER COLUMN "organizationId" DROP NOT NULL;

-- 3b. Catalog becomes tenant-owned. Both tables are empty at this point, so the
--     NOT NULL addition requires no backfill and no default value is invented.
ALTER TABLE "Category" ADD COLUMN "organizationId" TEXT NOT NULL;
ALTER TABLE "MenuItem" ADD COLUMN "organizationId" TEXT NOT NULL;

-- 3c. Order tenant ownership becomes mandatory.
ALTER TABLE "Order"
  ALTER COLUMN "organizationId" SET NOT NULL,
  ALTER COLUMN "outletId" SET NOT NULL,
  ALTER COLUMN "staffId" SET NOT NULL;

-- 3d. Indexes.
-- Per-tenant category slug uniqueness.
CREATE UNIQUE INDEX "Category_organizationId_slug_key" ON "Category"("organizationId", "slug");
-- Composite key that lets MenuItem carry a tenant-scoped foreign key.
CREATE UNIQUE INDEX "Category_id_organizationId_key" ON "Category"("id", "organizationId");
CREATE INDEX "MenuItem_organizationId_idx" ON "MenuItem"("organizationId");
CREATE INDEX "MenuItem_categoryId_organizationId_idx" ON "MenuItem"("categoryId", "organizationId");
-- Verified query patterns: POS outlet order list, Owner HQ counters.
CREATE INDEX "Order_organizationId_outletId_createdAt_idx" ON "Order"("organizationId", "outletId", "createdAt");
CREATE INDEX "Order_organizationId_status_idx" ON "Order"("organizationId", "status");

-- 3e. Foreign keys.
ALTER TABLE "Category" ADD CONSTRAINT "Category_organizationId_fkey"
  FOREIGN KEY ("organizationId") REFERENCES "Organization"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- TENANT-SCOPED COMPOSITE FOREIGN KEY.
-- A menu item's (categoryId, organizationId) must reference a category with the
-- SAME organizationId. Cross-tenant category assignment is therefore rejected by
-- PostgreSQL, not merely by application code.
ALTER TABLE "MenuItem" ADD CONSTRAINT "MenuItem_categoryId_organizationId_fkey"
  FOREIGN KEY ("categoryId", "organizationId") REFERENCES "Category"("id", "organizationId")
  ON DELETE RESTRICT ON UPDATE CASCADE;

-- staffId is now required, so the previous ON DELETE SET NULL is no longer valid.
-- Order history must retain its cashier; staff are deactivated, never hard-deleted.
ALTER TABLE "Order" ADD CONSTRAINT "Order_staffId_fkey"
  FOREIGN KEY ("staffId") REFERENCES "Staff"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. DATABASE-LEVEL INVARIANTS (CHECK constraints — hand-written)
--
-- Every constraint below encodes a rule that the current application ALREADY
-- enforces in src/lib/order-service.ts. None of them introduces a new tax
-- formula or a new business policy. See docs/ARCHITECTURE-DECISIONS.md.
--
-- These constraints are not expressed in prisma/schema.prisma because Prisma
-- does not model CHECK constraints. They are therefore invisible to Prisma's
-- schema diff and will not be dropped by `prisma migrate dev`.
-- ─────────────────────────────────────────────────────────────────────────────

-- 4a. Platform-role ownership invariant.
--     A platform role is NOT owned by a tenant.
--     A tenant role MUST be owned by exactly one organization.
ALTER TABLE "Role"
  ADD CONSTRAINT "Role_platform_org_check"
  CHECK (
    ("isPlatform" = true  AND "organizationId" IS NULL) OR
    ("isPlatform" = false AND "organizationId" IS NOT NULL)
  );

-- 4b. Menu monetary / stock sanity.
ALTER TABLE "MenuItem"
  ADD CONSTRAINT "MenuItem_price_non_negative_check"
  CHECK ("price" >= 0);

ALTER TABLE "MenuItem"
  ADD CONSTRAINT "MenuItem_stock_non_negative_check"
  CHECK ("stockCount" >= 0);

-- 4c. Order monetary sanity.
ALTER TABLE "Order"
  ADD CONSTRAINT "Order_amounts_non_negative_check"
  CHECK (
    "subtotal"     >= 0 AND
    "taxPb1"       >= 0 AND
    "totalAmount"  >= 0 AND
    "amountPaid"   >= 0 AND
    "changeAmount" >= 0
  );

-- totalAmount is defined as subtotal + taxPb1 (see prisma/schema.prisma comment
-- on Order.totalAmount and src/lib/order-service.ts).
-- REVISIT when discounts, service charge, or a configurable tax engine are added.
ALTER TABLE "Order"
  ADD CONSTRAINT "Order_total_consistency_check"
  CHECK ("totalAmount" = "subtotal" + "taxPb1");

-- Change is always the non-negative difference between cash tendered and total.
-- REVISIT when partial payments or split tender are introduced.
ALTER TABLE "Order"
  ADD CONSTRAINT "Order_change_consistency_check"
  CHECK ("changeAmount" = GREATEST("amountPaid" - "totalAmount", 0));

-- Cash tendered must cover the total. Non-cash methods carry amountPaid = 0.
-- REVISIT when pay-later / partial payment is introduced.
ALTER TABLE "Order"
  ADD CONSTRAINT "Order_cash_covers_total_check"
  CHECK ("paymentMethod" <> 'CASH' OR "amountPaid" >= "totalAmount");

-- 4d. Order line sanity.
ALTER TABLE "OrderItem"
  ADD CONSTRAINT "OrderItem_quantity_positive_check"
  CHECK ("quantity" > 0);

ALTER TABLE "OrderItem"
  ADD CONSTRAINT "OrderItem_amounts_non_negative_check"
  CHECK ("unitPrice" >= 0 AND "subtotal" >= 0);

-- A line subtotal is the unit price snapshot multiplied by quantity.
ALTER TABLE "OrderItem"
  ADD CONSTRAINT "OrderItem_subtotal_consistency_check"
  CHECK ("subtotal" = "quantity" * "unitPrice");


